#!/usr/bin/env bash
# Create roles and the demo database, load sql/*.sql, seed the first admin.
#
# Usage: scripts/db-init.sh [--reset]
#
#   --reset   drop and recreate the database (roles are kept)
#
# Connects with the standard libpq variables (PGHOST, PGPORT, PGUSER,
# PGPASSWORD). The connecting role must be a superuser: it creates roles and
# switches into demo_owner to create the schema.
#
# Secrets are never committed. If these are unset, random values are generated
# and stored in run/demo.env (mode 0600), which run-all.sh reads:
#   DEMO_SERVER_DB_PASSWORD      password of the demo_server login role
#   DEMO_CONTROLLER_DB_PASSWORD  password of the demo_controller login role
#   DEMO_ADMIN_PASSWORD          password of the API user "admin"
#
# Other variables:
#   PGDEMO_DB          database name (default: pgdemo)
#   PGDEMO_SERVER_BIN  binary used for `hash-password` (default: build/server/pgdemo-server)
#   PGDEMO_ENV_FILE    where generated settings are written (default: run/demo.env)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PGDEMO_ENV_FILE="${PGDEMO_ENV_FILE:-${ROOT}/run/demo.env}"

if [[ -f "${PGDEMO_ENV_FILE}" ]]; then
    # shellcheck disable=SC1090
    source "${PGDEMO_ENV_FILE}"
fi

PGDEMO_DB="${PGDEMO_DB:-pgdemo}"
PGDEMO_SERVER_BIN="${PGDEMO_SERVER_BIN:-${ROOT}/build/server/pgdemo-server}"
RESET=0

for arg in "$@"; do
    case "${arg}" in
        --reset) RESET=1 ;;
        -h|--help) sed -n '2,25p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "db-init: unknown argument: ${arg}" >&2; exit 2 ;;
    esac
done

log() { printf '[db-init] %s\n' "$*"; }
die() { printf '[db-init] ERROR: %s\n' "$*" >&2; exit 1; }

gen_secret() { openssl rand -base64 32 | tr -dc 'A-Za-z0-9' | head -c 24; }

command -v psql >/dev/null || die "psql not found (apt install postgresql-client)"
command -v openssl >/dev/null || die "openssl not found"

[[ "${PGDEMO_DB}" =~ ^[a-z_][a-z0-9_]{0,62}$ ]] || die "PGDEMO_DB must be a plain lower-case identifier"

DEMO_SERVER_DB_PASSWORD="${DEMO_SERVER_DB_PASSWORD:-$(gen_secret)}"
DEMO_CONTROLLER_DB_PASSWORD="${DEMO_CONTROLLER_DB_PASSWORD:-$(gen_secret)}"
DEMO_ADMIN_PASSWORD="${DEMO_ADMIN_PASSWORD:-$(gen_secret)}"

psql_su() { psql -X -v ON_ERROR_STOP=1 -q "$@"; }

is_super="$(psql_su -d postgres -tAc 'SELECT rolsuper FROM pg_roles WHERE rolname = current_user')"
[[ "${is_super}" == "t" ]] || die "the connecting role must be a superuser (PGUSER=${PGUSER:-$USER})"

log "roles (sql/00_roles.sql)"
psql_su -d postgres -f "${ROOT}/sql/00_roles.sql"

log "login role passwords"
# Read from the environment by psql itself (\getenv), never placed in argv.
DEMO_SERVER_DB_PASSWORD="${DEMO_SERVER_DB_PASSWORD}" \
DEMO_CONTROLLER_DB_PASSWORD="${DEMO_CONTROLLER_DB_PASSWORD}" \
psql_su -d postgres <<'SQL'
\getenv server_pw DEMO_SERVER_DB_PASSWORD
\getenv controller_pw DEMO_CONTROLLER_DB_PASSWORD
SET log_statement = 'none';
ALTER ROLE demo_server     PASSWORD :'server_pw';
ALTER ROLE demo_controller PASSWORD :'controller_pw';
SQL

if (( RESET )); then
    log "dropping database ${PGDEMO_DB}"
    psql_su -d postgres -c "DROP DATABASE IF EXISTS ${PGDEMO_DB} WITH (FORCE)"
fi

exists="$(psql_su -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname = '${PGDEMO_DB}'")"
if [[ "${exists}" != "1" ]]; then
    log "creating database ${PGDEMO_DB} (owner demo_owner)"
    psql_su -d postgres -c "CREATE DATABASE ${PGDEMO_DB} OWNER demo_owner"
fi

psql_su -d postgres <<SQL
REVOKE ALL ON DATABASE ${PGDEMO_DB} FROM PUBLIC;
GRANT CONNECT ON DATABASE ${PGDEMO_DB} TO demo_server, demo_controller;
SQL

for f in 01_data.sql 02_config.sql 03_users.sql 04_triggers.sql 05_views.sql; do
    log "loading sql/${f}"
    psql_su -d "${PGDEMO_DB}" -f "${ROOT}/sql/${f}"
done

has_admin="$(psql_su -d "${PGDEMO_DB}" -tAc "SELECT 1 FROM app_users WHERE role = 'admin' LIMIT 1")"
if [[ "${has_admin}" != "1" ]]; then
    [[ -x "${PGDEMO_SERVER_BIN}" ]] || die "no admin user yet and ${PGDEMO_SERVER_BIN} is missing; build first (cmake --build build)"
    log "seeding API user 'admin' (Argon2id)"
    PGDEMO_ADMIN_HASH="$(printf '%s' "${DEMO_ADMIN_PASSWORD}" | "${PGDEMO_SERVER_BIN}" hash-password)" \
    psql_su -d "${PGDEMO_DB}" <<'SQL'
\getenv hash PGDEMO_ADMIN_HASH
INSERT INTO app_users (username, password_hash, role)
VALUES ('admin', :'hash', 'admin')
ON CONFLICT (username) DO NOTHING;
SQL
fi

mkdir -p "$(dirname "${PGDEMO_ENV_FILE}")"
umask 077
cat > "${PGDEMO_ENV_FILE}" <<EOF
# Generated by scripts/db-init.sh. Do not commit.
PGDEMO_DB=${PGDEMO_DB}
PGDEMO_PGHOST=${PGDEMO_PGHOST:-127.0.0.1}
PGDEMO_PGPORT=${PGDEMO_PGPORT:-${PGPORT:-5432}}
DEMO_SERVER_DB_PASSWORD=${DEMO_SERVER_DB_PASSWORD}
DEMO_CONTROLLER_DB_PASSWORD=${DEMO_CONTROLLER_DB_PASSWORD}
DEMO_ADMIN_PASSWORD=${DEMO_ADMIN_PASSWORD}
EOF
chmod 600 "${PGDEMO_ENV_FILE}"

log "done. Settings in ${PGDEMO_ENV_FILE#"${ROOT}"/}"
psql_su -d "${PGDEMO_DB}" -c "SELECT target, applied_rate_ms, applied_amplitude, sync FROM v_dummy_config_sync_status ORDER BY target"
