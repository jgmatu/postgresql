#!/usr/bin/env bash
# Capture client/pgdemo.sh traffic on loopback and summarise it with tshark.
#
# Usage: scripts/capture.sh https|http
#
#   https   a TLS 1.3 server on 127.0.0.1:8443
#           writes data/https.pcapng, data/https.keylog, data/https-summary.txt
#   http    a plain server on 127.0.0.1:8080
#           writes data/http.pcapng, data/http-summary.txt
# The operational stack publishes HTTPS on 127.0.0.1:8080, so it is neither.
#
# The captured calls log in as a throwaway user (capture / capture-demo), so the
# files hold no real password. The admin calls that create and delete that user
# run before and after the capture. https.keylog holds the TLS secrets of this
# capture only; Wireshark uses it to decrypt https.pcapng.
#
# Needs dumpcap (group wireshark) and tshark.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DATA="${ROOT}/data"
CLIENT="${ROOT}/client/pgdemo.sh"
CA="${ROOT}/run/keys/tls.crt"
CAPTURE_USER=capture
CAPTURE_PASSWORD=capture-demo

die() { printf '[capture] ERROR: %s\n' "$*" >&2; exit 1; }
say() { printf '[capture] %s\n' "$*"; }

case "${1:-}" in
    https) MODE=https; PORT=8443; CLIENT_ARGS=() ;;
    http) MODE=http; PORT=8080; CLIENT_ARGS=(--http) ;;
    -h|--help) sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "usage: scripts/capture.sh https|http" ;;
esac
URL="${MODE}://127.0.0.1:${PORT}"

command -v dumpcap >/dev/null || die "dumpcap not found (apt install wireshark-common)"
command -v tshark >/dev/null || die "tshark not found (apt install tshark)"
[[ -f "${ROOT}/run/demo.env" ]] || die "run/demo.env not found; run scripts/db-init.sh first"
# shellcheck disable=SC1091
source "${ROOT}/run/demo.env"

curl -sf --cacert "${CA}" -o /dev/null "${URL}/api/health" ||
    die "no server on ${URL}"

PCAP="${DATA}/${MODE}.pcapng"
KEYLOG="${DATA}/${MODE}.keylog"
SUMMARY="${DATA}/${MODE}-summary.txt"
mkdir -p "${DATA}"
rm -f "${PCAP}" "${KEYLOG}" "${SUMMARY}"

WORK="$(mktemp -d)"
dumpcap_pid=""
cleanup() {
    [[ -n "${dumpcap_pid}" ]] && kill -INT "${dumpcap_pid}" 2>/dev/null && wait "${dumpcap_pid}" 2>/dev/null
    rm -rf "${WORK}"
}
trap cleanup EXIT

client() { "${CLIENT}" "${CLIENT_ARGS[@]}" "$@"; }
as_admin() { PGDEMO_TOKEN="${WORK}/admin.token" client "$@"; }
as_capture() { PGDEMO_TOKEN="${WORK}/capture.token" client "$@"; }

say "creating the throwaway user '${CAPTURE_USER}' (not captured)"
PGDEMO_PASSWORD="${DEMO_ADMIN_PASSWORD}" as_admin login admin >/dev/null 2>&1 || die "admin login failed"
as_admin users del "${CAPTURE_USER}" >/dev/null 2>&1 || true
PGDEMO_NEW_PASSWORD="${CAPTURE_PASSWORD}" as_admin users add "${CAPTURE_USER}" normal >/dev/null 2>&1 ||
    die "cannot create user ${CAPTURE_USER}"

say "capturing tcp port ${PORT} on lo into ${PCAP#"${ROOT}"/}"
dumpcap -q -i lo -f "tcp port ${PORT}" -w "${PCAP}" 2>"${WORK}/dumpcap.err" &
dumpcap_pid=$!
for _ in $(seq 50); do
    grep -q "Capturing on" "${WORK}/dumpcap.err" 2>/dev/null && break
    kill -0 "${dumpcap_pid}" 2>/dev/null || die "dumpcap failed: $(cat "${WORK}/dumpcap.err")"
    sleep 0.1
done
sleep 0.3

[[ "${MODE}" == https ]] && export SSLKEYLOGFILE="${KEYLOG}"
{
    for args in "health" "login ${CAPTURE_USER}" "me" "data dummy1" "config status"; do
        printf '\n$ client/pgdemo.sh %s\n' "${CLIENT_ARGS[*]:+${CLIENT_ARGS[*]} }${args}"
        # shellcheck disable=SC2086
        PGDEMO_PASSWORD="${CAPTURE_PASSWORD}" as_capture ${args} 2>&1 || true
    done
    if [[ "${MODE}" == https ]]; then
        printf '\n$ curl --tls-max 1.2 %s/api/health   (must fail: the server is TLS 1.3 only)\n' "${URL}"
        if curl -sS --cacert "${CA}" --tls-max 1.2 -o /dev/null "${URL}/api/health" 2>&1; then
            echo "UNEXPECTED: TLS 1.2 handshake succeeded"
        fi
    fi
} > "${WORK}/client.txt"
unset SSLKEYLOGFILE

sleep 0.5
kill -INT "${dumpcap_pid}"
wait "${dumpcap_pid}" 2>/dev/null || true
dumpcap_pid=""
chmod 644 "${PCAP}"

say "deleting '${CAPTURE_USER}' (not captured)"
as_admin users del "${CAPTURE_USER}" >/dev/null 2>&1 || say "warning: could not delete ${CAPTURE_USER}"

tls_opts=()
[[ "${MODE}" == https ]] && tls_opts=(-o "tls.keylog_file:${KEYLOG}")
section() { printf '\n==== %s ====\n' "$1"; }
{
    printf 'pgdemo %s capture: %s, loopback tcp port %s\n' "${MODE}" "${PCAP#"${ROOT}"/}" "${PORT}"
    printf 'Generated by scripts/capture.sh %s on %s\n' "${MODE}" "$(date -u +%FT%TZ)"

    section "Client commands and output"
    cat "${WORK}/client.txt"

    if [[ "${MODE}" == https ]]; then
        section "TLS handshakes (ClientHello, ServerHello, alerts)"
        echo "frame  client_port  message      tls_version  key_share_groups / alert"
        tshark -r "${PCAP}" -Y 'tls.handshake.type == 1 || tls.handshake.type == 2 || tls.alert_message' \
            -T fields -E separator=/t -E aggregator=, -E occurrence=a \
            -e frame.number -e tcp.srcport -e tcp.dstport -e tls.handshake.type \
            -e tls.handshake.extensions.supported_version -e tls.handshake.extensions_key_share_group \
            -e tls.alert_message.desc |
            awk -F'\t' -v port="${PORT}" '
                function group(g,   n, i, out, parts, name) {
                    n = split(g, parts, ",")
                    for (i = 1; i <= n; i++) {
                        name = parts[i]
                        if (name == "4588") name = "X25519MLKEM768"
                        else if (name == "29") name = "X25519"
                        else if (name == "23") name = "secp256r1"
                        else if (name == "24") name = "secp384r1"
                        out = out (i > 1 ? "," : "") name
                    }
                    return out
                }
                {
                    cport = ($2 == port) ? $3 : $2
                    if ($4 == "1") msg = "ClientHello"
                    else if ($4 == "2") msg = "ServerHello"
                    else msg = "Alert"
                    ver = $5
                    gsub(/0x0304/, "TLS1.3", ver); gsub(/0x0303/, "TLS1.2", ver)
                    if (ver == "" && msg == "ClientHello") ver = "TLS1.2 max"
                    detail = ($7 != "") ? "alert " $7 : group($6)
                    printf "%-6s %-12s %-12s %-12s %s\n", $1, cport, msg, ver, detail
                }'
        echo
        echo "Alert 70 is protocol_version: the client capped at TLS 1.2 is refused."

        section "Negotiated key exchange (ServerHello, decoded by tshark)"
        tshark -r "${PCAP}" -Y 'tls.handshake.type == 2' -V |
            grep -E 'Supported Version:|Key Share Entry: Group|Cipher Suite:' | sed 's/^ *//' | sort | uniq -c
    fi

    section "HTTP $([[ ${MODE} == https ]] && echo 'decrypted with data/https.keylog' || echo 'in clear text')"
    tshark -r "${PCAP}" "${tls_opts[@]}" -Y http -T fields -E separator=/t \
        -e frame.number -e tcp.srcport -e _ws.col.Info

    section "POST /api/auth/login bodies $([[ ${MODE} == https ]] && echo '(decrypted; encrypted on the wire)' || echo '(as they travel on the wire)')"
    tshark -r "${PCAP}" "${tls_opts[@]}" -Y 'http.request.uri == "/api/auth/login"' -T fields \
        -e http.file_data | xxd -r -p 2>/dev/null || true
    echo
} > "${SUMMARY}"

say "wrote ${PCAP#"${ROOT}"/}$([[ ${MODE} == https ]] && echo ", ${KEYLOG#"${ROOT}"/}") and ${SUMMARY#"${ROOT}"/}"
